// Command restaurant runs the demo restaurant service that integrates with the
// platform partner API on behalf of a single venue.
package main

import (
	"log/slog"
	"os"
)

func main() {
	logger := slog.New(slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{
		Level: slog.LevelInfo,
	}))
	slog.SetDefault(logger)

	slog.Info("restaurant service starting")
}
